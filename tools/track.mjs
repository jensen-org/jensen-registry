import { copyFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { ROOT, SCHEMA_VERSION, dump, readYaml, writeText } from "../lib.mjs";
import { generate } from "./generate.mjs";
import { fetchPackages, resolveUpstreams } from "./upstream.mjs";

export const LEGACY_COPIES = ["tools.yaml", "upstreams.yaml"];

export const HEAD_NOTE = "# generated by tools/track.mjs from the mason release pinned in tools/upstreams.yaml, tools/definitions and tools/installers.yaml, do not edit";

export const DEFINITIONS_DIR = "tools/definitions";

export function readDefinitions() {
  return readdirSync(join(ROOT, DEFINITIONS_DIR))
    .filter((name) => name.endsWith(".yaml"))
    .sort()
    .map((name) => ({ name, definition: readYaml(`${DEFINITIONS_DIR}/${name}`) }));
}

export function build(packages) {
  const { languages } = readYaml("tools/languages.yaml");
  const installers = readYaml("tools/installers.yaml");
  const definitions = readDefinitions().map(({ definition }) => definition);
  const result = generate({ packages, languages, definitions, installers });
  return { ...result, installers };
}

export function renderHead({ languages, tools, installers }) {
  return `${HEAD_NOTE}\n${dump({ schema_version: SCHEMA_VERSION, languages, tools, installers })}`;
}

export async function trackTools({ warn }) {
  const upstreams = await resolveUpstreams();
  const result = build(await fetchPackages(upstreams));
  writeText("tools/upstreams.yaml", dump(upstreams));
  writeText("tools/tools.yaml", renderHead(result));
  for (const [reason, names] of Object.entries(result.skipped).sort()) warn(`${names.length} mason packages left out, ${reason}`);
  return result;
}

export function copyLegacyTools() {
  for (const name of LEGACY_COPIES) copyFileSync(join(ROOT, "tools", name), join(ROOT, name));
}
